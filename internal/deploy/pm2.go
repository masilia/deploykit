// ecosystemApp mirrors one pm2 app entry; field order is the order written to the file.
type ecosystemApp struct {
	Name             string            `json:"name"`
	Cwd              string            `json:"cwd"`
	Script           string            `json:"script"`
	Env              map[string]string `json:"env"`
	MaxMemoryRestart string            `json:"max_memory_restart,omitempty"`
	Time             bool              `json:"time"`
}

// Ecosystem renders ecosystem.config.cjs from the manifest. Templates in name and env are resolved with vars; every
// string is JSON-encoded, so a value can never break out of the file. The app runs from the current link of layout.
func Ecosystem(cfg *manifest.PM2, l Layout, vars tmpl.Vars) (string, error) {
	name, err := tmpl.Render(cfg.Name, vars, false)
	if err != nil {
		return "", fmt.Errorf("runtime.name: %w", err)
	}
	if name == "" || !pm2NamePattern(name) {
		return "", fmt.Errorf("runtime.name %q must be letters, digits, dots, dashes or underscores", name)
	}
	env := make(map[string]string, len(cfg.Env))
	for k, v := range cfg.Env {
		r, err := tmpl.Render(v, vars, false)
		if err != nil {
			return "", fmt.Errorf("runtime.env.%s: %w", k, err)
		}
		env[k] = r
	}
	app := ecosystemApp{
		Name:             name,
		Cwd:              l.CurrentLink(),
		Script:           cfg.Entry,
		Env:              env,
		MaxMemoryRestart: cfg.MaxMemory,
		Time:             true,
	}
	body, err := json.MarshalIndent(map[string][]ecosystemApp{"apps": {app}}, "", "  ")
	if err != nil {
		return "", err
	}
	return "// Generated by deploykit. Do not edit: it is replaced on every deploy.\nmodule.exports = " + string(body) + ";\n", nil
}

func pm2NamePattern(s string) bool {
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '.', r == '-', r == '_':
		default:
			return false
		}
	}
	return true
}

// PM2 drives pm2 as the site user over a transport whose Prelude loads node (nvm).
type PM2 struct {
	T    transport.Transport
	Name string
	L    Layout
}

// Managed reports whether pm2 already runs the app. `pm2 pid` is read-only and never starts a daemon.
func (p PM2) Managed(ctx context.Context) (bool, error) {
	res, err := p.T.Run(ctx, transport.Spec{
		Script: `pm2 pid "$DK_NAME" 2>/dev/null | head -1 || true` + "\n",
		Env:    map[string]string{"DK_NAME": p.Name},
	})
	if err != nil {
		return false, err
	}
	pid := strings.TrimSpace(res.Stdout)
	return pid != "" && pid != "0", nil
}

// Reload starts the app or reloads it with the new release and saves the process list.
func (p PM2) Reload(ctx context.Context) error {
	_, err := p.T.Run(ctx, transport.Spec{
		Script: `cd "$DK_ROOT" && pm2 startOrReload ecosystem.config.cjs --update-env && pm2 save` + "\n",
		Env:    map[string]string{"DK_ROOT": p.L.Root},
	})
	return err
}

// Logs returns the last n log lines without following.
func (p PM2) Logs(ctx context.Context, n int) (string, error) {
	res, err := p.T.Run(ctx, transport.Spec{
		Script: `pm2 logs "$DK_NAME" --lines "$DK_LINES" --nostream 2>&1 || true` + "\n",
		Env:    map[string]string{"DK_NAME": p.Name, "DK_LINES": strconv.Itoa(n)},
	})
	return res.Stdout, err
}

// UploadEcosystem writes the pm2 configuration file next to releases/.
func (p PM2) UploadEcosystem(ctx context.Context, content string) error {
	return writeFile(ctx, p.T, p.L.Ecosystem(), content)
}

// Healthy asks the server itself to fetch the app, up to h.Tries times h.Interval apart, so the check works whatever
// the firewall allows. It returns the last HTTP code seen.
func Healthy(ctx context.Context, t transport.Transport, port string, h manifest.Health) (code string, ok bool, err error) {
	if _, convErr := strconv.Atoi(port); convErr != nil {
		return "", false, fmt.Errorf("invalid app port %q", port)
	}
	if !strings.HasPrefix(h.Path, "/") {
		return "", false, fmt.Errorf("health path %q must start with /", h.Path)
	}
	script := `code=000
i=0
while [ "$i" -lt "$DK_TRIES" ]; do
  code=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$DK_PORT$DK_PATH" || true)
  [ "$code" = "$DK_EXPECT" ] && { echo "$code"; exit 0; }
  i=$((i + 1))
  sleep "$DK_SLEEP"
done
echo "$code"
exit 1
`
	res, runErr := t.Run(ctx, transport.Spec{Script: script, Env: map[string]string{
		"DK_TRIES":  strconv.Itoa(h.Tries),
		"DK_PORT":   port,
		"DK_PATH":   h.Path,
		"DK_EXPECT": strconv.Itoa(h.Expect),
		"DK_SLEEP":  strconv.FormatFloat(h.Interval.Seconds(), 'f', -1, 64),
	}})
	code = strings.TrimSpace(res.Stdout)
	if runErr == nil {
		return code, true, nil
	}
	if res.ExitCode == 1 {
		return code, false, nil
	}
	return code, false, runErr
}
